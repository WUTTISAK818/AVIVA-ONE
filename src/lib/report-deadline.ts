// เส้นตายส่งรายงานประจำวัน — แหล่งความจริงเดียวของทั้งแอป
//
// ปัญหาที่ไฟล์นี้กันไว้ (พบจากการตรวจประวัติจริง 24 ต.ค. 69 ตามที่ Pom สั่ง):
//
// 1) เคยมี "เส้นตาย" อยู่ 2 ค่าในโค้ดคนละที่ และไม่ตรงกัน
//      · src/app/reports/page.tsx        → ตัดที่ 19:00
//      · src/components/ReportSubmitModal.tsx → ตัดที่ 18:00
//    ผลคือรายงานที่ส่งเวลา 18:00-18:59 ถูกตีว่าล่าช้าหรือไม่ ขึ้นกับว่าส่งผ่านหน้าจอไหน
//    จากประวัติจริง 305 ฉบับ: 41 ฉบับถูกตีว่าล่าช้าทั้งที่ส่งก่อน 19:00 ตามกติกาที่ประกาศไว้
//    (เดียร์ 30 · พีท 7 · ฟ้า 4) — เป็นความผิดของโค้ด ไม่ใช่ของพนักงาน
//
// 2) ทั้งสองที่ใช้ `new Date().getHours()` ซึ่งอ่านเวลาตาม "โซนเวลาของเครื่องผู้ใช้"
//    ถ้าโทรศัพท์ตั้งโซนเวลาผิด/ไปต่างประเทศ พนักงานจะถูกตีว่าล่าช้าทั้งที่ส่งตรงเวลาไทย
//    → ไฟล์นี้ใช้เวลาไทยตรง ๆ เสมอ ไม่ขึ้นกับเครื่อง
//
// เปลี่ยนเส้นตาย = แก้บรรทัดเดียวที่ REPORT_DEADLINE ด้านล่าง แล้วทุกหน้าจอเปลี่ยนตามทันที
import { thaiTimeStr } from "./thai-date";

/** เส้นตายส่งรายงานประจำวัน (เวลาไทย "HH:MM")
 *
 *  ตั้งที่ 19:30 จากประวัติจริง 305 ฉบับ (30 เม.ย. – 24 ต.ค. 69 · 5 คน):
 *    เลิกงาน 17:00 · ส่งเร็วที่สุดที่เคยมี 16:58 · ค่ากลาง 18:00
 *    p95 รายคน: เดียร์ 18:17 · ฟ้า 19:08 · พีท 19:17
 *  19:30 อยู่เหนือ p95 ของทุกคน → คนที่ทำงานตามปกติจะไม่ติดประวัติล่าช้า
 *  แต่ยังจับของที่ช้าจริงได้ (เหลือ 3.0% = 9 ฉบับ กระจาย พีท 4 · ฟ้า 4 · เดียร์ 1)
 *
 *  ถ้าตัดที่ 19:00 จะเหลือล่าช้า 18 ฉบับ แต่ 10 ใน 18 เป็นของพีทคนเดียว
 *  เพราะ p95 ของพีทคือ 19:17 → เป็นการลงโทษรูปแบบการทำงานปกติของเขา ไม่ใช่ความสะเพร่า
 */
export const REPORT_DEADLINE = "19:30";

/** เวลาที่ระบบเตือนคนที่ยังไม่ส่ง (เวลาไทย) — ตั้งไว้ใน vercel.json ด้วย */
export const REPORT_REMINDER_TIME = "18:00";

/** ตอนนี้ (เวลาไทย) เลยเส้นตายหรือยัง — ใช้ตัดสินว่ารายงานที่ส่ง ณ ตอนนี้เป็น late ไหม */
export function isPastReportDeadline(): boolean {
  return thaiTimeStr() >= REPORT_DEADLINE;
}

/** สถานะของรายงานที่ส่ง ณ ตอนนี้
 *  ส่งย้อนหลังไม่นับล่าช้า เพราะมีป้าย is_backdated บอกอยู่แล้ว
 *  และเวลาที่กดส่งย้อนหลังไม่ได้สะท้อนว่าวันนั้นทำงานเสร็จกี่โมง */
export function reportSubmitStatus(isBackdated: boolean): "submitted" | "late" {
  return !isBackdated && isPastReportDeadline() ? "late" : "submitted";
}
